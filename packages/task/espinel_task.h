/* The task package's C (task.c), which every firmware carries: main/main.c
   starts the main program through it, every VM's main/vm_entry.c reports
   to it, and the packages' C reaches the calling program's VM through it.

   A VM is one Ruby program built with its own copy of Spinel's runtime:
   "main", the entry point, is VM 0, then one for each tasks/<name>.rb
   beside it, in the order of their names. Each runs on a FreeRTOS task of
   its own.

   The packages' C is linked once for the whole firmware, so it must not
   name Spinel's globals (each VM has its own, and they are local to it):
   it goes through espinel_vm_current() and espinel_ffi_bin_len() instead.
   What it keeps for one program between two calls (a result buffer, a
   table of sessions) it keeps in espinel_vm_local(). */
#ifndef ESPINEL_TASK_H
#define ESPINEL_TASK_H
#include <stddef.h>
#include <stdint.h>

/* What a VM shows the shared C of its runtime's state: its own copies of
   Spinel's globals, filled in by its vm_entry.c as it starts. */
typedef struct {
  int *ffi_bin_len;                    /* sp_ffi_bin_len: a :binstr return's length */
  size_t *gc_bytes, *gc_threshold;     /* sp_gc_bytes, sp_gc_threshold */
  unsigned long long *gc_collections;  /* sp_gc_stat_collections */
  unsigned long long *gc_fulls;        /* sp_gc_stat_fulls */
  uintptr_t (*stack_limit)(void);      /* where SystemStackError comes (stack_check.c) */
  unsigned stack_size;                 /* its task's stack, in bytes */
} espinel_vm;

/* the table of VMs, generated by main/CMakeLists.txt (vm_table.c) */
typedef struct {
  const char *name;
  int (*run)(espinel_vm *vm, const char *name, unsigned stack_size);
} espinel_vm_def;
extern const espinel_vm_def espinel_vm_defs[];
extern const int espinel_vm_def_count;

enum { ESPINEL_TASK_IDLE, ESPINEL_TASK_RUNNING, ESPINEL_TASK_FINISHED };

/* Sets the table up, before any VM starts. Answers 0, or -1 out of
   memory. */
int espinel_task_init(void);

/* Starts VM id on a task of its own: on core 0 or 1, or either (-1). A VM
   runs once a boot, since Spinel's state is not reset. Answers 0, or
   -1 no such VM, -2 started before, -3 no such core, -4 out of memory. */
int espinel_task_start(int id, int core, int priority, int stack_size);

/* how many VMs are running (the GC shares the heap out among them) */
unsigned espinel_task_running(void);

/* Every VM collects at its next allocation: the heap is short (a VM's
   malloc failed), or the VMs running have changed and each should share
   the room out again. A VM blocked in a wait collects when it next
   allocates. */
void espinel_task_pressure(void);

/* The VM running on the calling task, NULL on any other task. */
const espinel_vm *espinel_vm_current(void);

/* Sets the calling VM's sp_ffi_bin_len: the length of the bytes a
   :binstr function returns. */
void espinel_ffi_bin_len(int len);

/* The calling VM's block of size bytes for key (any address unique to the
   caller, a static of its own), zeroed when first asked for. When the
   VM's program ends, fini (when not NULL) is called with it, for what it
   points to, and the block is freed. NULL out of memory or outside a
   VM. */
void *espinel_vm_local(const void *key, size_t size, void (*fini)(void *block));

#endif
